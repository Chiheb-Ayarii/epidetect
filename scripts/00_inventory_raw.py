"""Inventory of the raw NIX/HDF5 files: one row per patient and recording block.

This is a read-only inspection tool used to write docs/DATA_NOTES.md. It deliberately uses
only h5py (no project code) so that it documents the raw files *before* any loader exists.

Usage:
    python scripts/00_inventory_raw.py --raw-dir data/raw --out docs/data_inventory.md
"""

from __future__ import annotations

import argparse
from pathlib import Path

import h5py
import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
BLOCKS = {
    "pre": "Data_Pre_Resection_Bipolar_Montage",
    "post": "Data_Post_Resection_Bipolar_Montage",
}
SIGNAL_ARRAY = "ECoG_Bipolar_Channels"
FR_GROUP = "groups/FR markings/tags"


def read_property(dataset: h5py.Dataset) -> str | float:
    """Decode a NIX metadata property.

    NIX stores each property as an array of compound records with a ``value`` field.
    Some strings were saved character by character (one record per letter), so we join them.
    """
    values = dataset[()]["value"]
    if values.dtype == object:
        return "".join(v.decode("latin-1") if isinstance(v, bytes) else str(v) for v in values)
    return float(values[0])


def read_patient_metadata(f: h5py.File) -> dict[str, str | float]:
    """Return the properties of the ``metadata/Patient`` section and the electrode type."""
    props = f["metadata/Patient/properties"]
    meta = {name: read_property(props[name]) for name in props}
    setup = f["metadata/General/sections/Recording setup/properties"]
    meta["Electrode type"] = read_property(setup["Electrode type"])
    return meta


def summarize_block(block: h5py.Group) -> dict[str, float | int | str]:
    """Number of channels, duration, sampling rate and FR markings of one recording block."""
    array = block[f"data_arrays/{SIGNAL_ARRAY}"]
    n_channels, n_samples = array["data"].shape
    dt = float(array["dimensions/2"].attrs["sampling_interval"])
    tags = block[FR_GROUP] if FR_GROUP in block else {}
    durations_ms = [1000 * float(tags[t]["extent"][()][1]) for t in tags]
    channels_with_fr = {int(tags[t]["position"][()][0]) for t in tags}
    return {
        "n_channels": n_channels,
        "duration_s": round(n_samples * dt, 1),
        "fs_hz": round(1.0 / dt),
        "n_fr": len(durations_ms),
        "n_channels_with_fr": len(channels_with_fr),
        "fr_dur_median_ms": round(float(np.median(durations_ms)), 1) if durations_ms else np.nan,
    }


def build_inventory(raw_dir: Path) -> pd.DataFrame:
    """One row per (patient, block) with metadata and summary statistics."""
    rows = []
    for path in sorted(raw_dir.glob("Data_Patient_*.h5")):
        patient = path.stem.split("_")[-1]
        with h5py.File(path, "r") as f:
            meta = read_patient_metadata(f)
            for session, block_name in BLOCKS.items():
                rows.append(
                    {
                        "patient": patient,
                        "session": session,
                        "age": int(meta["Age"]),
                        "electrode": meta["Electrode type"],
                        "etiology": meta["Etiology"],
                        "resection_area": meta["Resection area"],
                        "ilae": int(meta["Outcome ILAE"]),
                        "follow_up_months": int(meta["Follow-up period"]),
                        **summarize_block(f["data"][block_name]),
                    }
                )
    return pd.DataFrame(rows)


def to_markdown(df: pd.DataFrame) -> str:
    """Render the inventory and a few totals as a Markdown document."""
    patients = df.drop_duplicates("patient")
    pre, post = df[df.session == "pre"], df[df.session == "post"]
    lines = [
        "# Raw data inventory",
        "",
        "Generated by `scripts/00_inventory_raw.py`. Do not edit by hand.",
        "",
        "## Totals",
        "",
        f"- Patients: {len(patients)}",
        f"- Seizure-free (ILAE 1): {(patients.ilae == 1).sum()}; "
        f"not seizure-free (ILAE > 1): {(patients.ilae > 1).sum()}",
        f"- Pre-resection: {pre.n_channels.sum()} bipolar channels, "
        f"{pre.duration_s.sum() / 60:.1f} min, {pre.n_fr.sum()} FR markings, "
        f"{(pre.n_fr > 0).sum()} patients with at least one FR",
        f"- Post-resection: {post.n_channels.sum()} bipolar channels, "
        f"{post.duration_s.sum() / 60:.1f} min, {post.n_fr.sum()} FR markings, "
        f"{(post.n_fr > 0).sum()} patients with at least one FR",
        f"- Sampling rates found: {sorted(df.fs_hz.unique().tolist())} Hz",
        "",
        "## Per patient and session",
        "",
        "| " + " | ".join(df.columns) + " |",
        "|" + "---|" * len(df.columns),
    ]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--raw-dir", type=Path, default=REPO_ROOT / "data" / "raw")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "data_inventory.md")
    args = parser.parse_args()
    df = build_inventory(args.raw_dir)
    # newline="\n": keep LF line endings on Windows too (matches .gitattributes).
    args.out.write_text(to_markdown(df), encoding="utf-8", newline="\n")
    print(df.to_string(index=False))


if __name__ == "__main__":
    main()
